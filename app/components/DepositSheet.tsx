import {useCallback, useEffect, useRef, useState} from 'react';
import {View, Text, Pressable, ActivityIndicator, Platform} from 'react-native';
import {QrCode} from './QrCode';
import {C} from '../config/palette';
import {S} from '../styles';
import {POLL, DEPOSIT_TIMEOUT_MS, DEPOSIT_ADDRESS_TIMEOUT_MS, QR_SIZE_SMALL} from '../config/constants';
import {fmtAsset} from '../lib/format';
import {cmpRaw} from '../lib/amount';
import type {Identity} from '../lib/types';
import type {CurrencyDescriptor, FamilyDisplay} from '../config/catalog';
import {type DepositInfo, depositInfo} from '../services/relay';
import {railBtcDepositAddress, railBalanceOf} from '../services/rail';
import {useEscapeToClose} from '../hooks/useHotkeys';
import {useCopyFeedback} from '../hooks/useCopyFeedback';
import {withTimeout} from '../lib/timeout';
import {IconCheck, IconCopy} from './icons';

/**
 * ckBTC-style deposit sheet (IC user-principal rail). The deposit address is generated by the
 * ckBTC minter's get_btc_address for THIS user's own principal (owner = self_authenticating(device
 * pubkey)) — a signed query straight to /api/v2, no relay, no facade subaccount. Mint detection is
 * an honest balance recheck: poll icrc1_balance_of on the ledger and compare against the baseline
 * captured at first successful read (the facade-subaccount pending-UTXO progress cue is gone —
 * the minter's per-UTXO view lived behind facade custody). Fee/min/confirmations still come from
 * the relay's read-only /deposit/info (display-only network facts).
 */
// H5: plain-language deposit errors. Two cases the user can act on: (1) transient — the address
// couldn't be loaded (network/timeout/gateway down); (2) no minter — this asset has no deposit
// minter configured in the catalog.
const TRANSIENT_DEPOSIT_ERR = "Couldn't load your deposit address. Check your connection and try again.";
const NO_MINTER_DEPOSIT_ERR = "This asset isn't available for deposits yet.";
export function DepositSheet({identity, relayUrl, catalog, currency, display, onClose}: {identity: Identity; relayUrl: string; catalog: CurrencyDescriptor[]; currency: number; display: FamilyDisplay; onClose: () => void}) {
  const [info, setInfo] = useState<DepositInfo | null>(null);
  const [address, setAddress] = useState<string | null>(null);
  const [mintedTotal, setMintedTotal] = useState<string | null>(null);
  // Balance baseline (captured at the first successful ledger read while the sheet is open).
  // minted = current balance strictly ABOVE the baseline → the mint landed while watching.
  const baselineRef = useRef<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [err, setErr] = useState<string | null>(null);
  const {copied, copy: doCopy} = useCopyFeedback();
  // Manual "Check now": debounced + disabled while a refresh is in-flight (reuses the poll's fetch).
  const [checkBusy, setCheckBusy] = useState(false);

  const desc = catalog.find(c => c.currency === currency) ?? null;

  // Escape closes the sheet (seed of the keyboard-shortcuts surface — plan flow 14).
  useEscapeToClose(onClose);

  // The deposit ADDRESS is the critical path (it's the thing the user came for); deposit INFO
  // (fee/min/confirmations) is supplementary. They are fetched on SEPARATE controllers so the slow
  // relay info proxy can never abort the address (a signed query, typically ~1–2s). The sheet
  // tolerates a null `info` (renders "none"/"no minimum" for fee/min), so a best-effort info miss
  // degrades gracefully instead of hiding the address.
  useEffect(() => {
    let alive = true;
    const {signal, cancel} = withTimeout(DEPOSIT_ADDRESS_TIMEOUT_MS);
    (async () => {
      setLoading(true); setErr(null);
      try {
        const minter = desc?.minter ?? null;
        // H5: no minter registered for this currency → the asset has no deposit rail configured.
        if (!minter) { if (alive) setErr(NO_MINTER_DEPOSIT_ERR); return; }
        // Signed query at THIS user's principal — the minter accepts arbitrary owners (proven in
        // mock); the address pays out to Account{owner: user principal}, never facade custody.
        const a = await railBtcDepositAddress(identity.secretHex, minter, signal);
        if (!alive) return;
        if (!a) { setErr(TRANSIENT_DEPOSIT_ERR); return; } // unreachable/query-rejected
        setAddress(a);
      } catch (e: unknown) {
        if (alive) setErr(TRANSIENT_DEPOSIT_ERR);
      } finally {
        if (alive) setLoading(false);
        cancel();
      }
    })();
    return () => { alive = false; };
  }, [identity.secretHex, desc]);

  // Best-effort deposit info (fee / min / confirmations). Independent controller + timeout so a slow
  // or failing info fetch never blocks the address above. `info` stays null on a miss → the sheet
  // renders "none"/"no minimum" for the fee/min fields (graceful, not an error).
  useEffect(() => {
    let alive = true;
    const {signal, cancel} = withTimeout(DEPOSIT_TIMEOUT_MS);
    (async () => {
      try {
        const i = await depositInfo(relayUrl, currency, signal);
        if (alive) setInfo(i);
      } catch (e) { console.warn('depositInfo fetch failed: ', e); }
      finally { cancel(); }
    })();
    return () => { alive = false; };
  }, [relayUrl, currency]);

  // ONE refresh function reused by BOTH the 10s poll and the manual "Check now" button — single
  // source of truth. Honest mint detection: signed icrc1_balance_of against the ledger; the first
  // successful read is the baseline, any strictly-higher later read = the mint landed (delta shown).
  const refreshNow = useCallback(async (manual: boolean) => {
    if (manual) {
      setCheckBusy(true);
    }
    try {
      const ledger = desc?.ledger ?? '';
      if (!ledger) return;
      const bal = await railBalanceOf(identity.secretHex, ledger);
      if (bal != null) {
        const base = baselineRef.current;
        if (base == null) {
          baselineRef.current = bal; // first successful read while open — the watching baseline
        } else if (cmpRaw(bal, base) > 0) {
          // MC1: raw-u64 decimal STRINGS; the delta via BigInt (both are digit strings).
          setMintedTotal((BigInt(bal) - BigInt(base)).toString());
        }
      }
    } catch (e) { console.warn('deposit balance recheck failed: ', e); }
    finally {
      if (manual) {
        setCheckBusy(false);
      }
    }
  }, [identity.secretHex, desc]);

  // Poll every POLL.deposit while open; cleans up on close.
  useEffect(() => {
    let alive = true;
    const poll = () => { if (alive) { refreshNow(false); } };
    poll(); const id = setInterval(poll, POLL.deposit);
    return () => { alive = false; clearInterval(id); };
  }, [refreshNow]);

  const copy = useCallback(async () => {
    if (address) { await doCopy(address); }
  }, [address, doCopy]);

  const required = info?.min_confirmations ?? 0;
  const estMin = required > 0 ? required * display.blockMin : 0;
  // C3: never render a raw "0.00000000 BTC" — when a fee/min value is zero (the test minter /
  // FakeLedger returns zeros; a future no-fee asset) show an explicit word for that part and format
  // normally only when non-zero. The labels stay so the fields remain visible; only the bogus zero
  // amount (8 trailing zeros) is suppressed — a premium app never shows that to a user. The word
  // (vs a bare "—") keeps the field from reading as "broken/loading" on a money screen: fee →
  // "none", min → "no minimum". MC1 units 2-4: fee/min are raw-u64 decimal STRINGS; zero-presence
  // via `cmpRaw` (BigInt) — never `> 0`.
  const feeVal = info && cmpRaw(info.deposit_fee, '0') > 0 ? fmtAsset(info.deposit_fee, display.amountDecimals, display.nativeAsset) : 'none';
  const minVal = info && info.deposit_min_amount != null && cmpRaw(info.deposit_min_amount, '0') > 0 ? fmtAsset(info.deposit_min_amount, display.amountDecimals, display.nativeAsset) : 'no minimum';

  // The body content is rendered inline in the Receive tab's "My address" sub-mode (the tab body
  // already provides the scroll surface + the overlay chrome). `onClose` is wired to the inner
  // "Done" buttons so a completed/esc flow returns to the request sub-mode.
  const body = (
    <>
      {loading ? (
        <View style={S.centerAll}>
          <ActivityIndicator color={C.brand} />
          <Text style={S.dim2}>Fetching your deposit address…</Text>
        </View>
      ) : err || !address ? (
        <View style={S.centerAll}>
          {/* H5: the message already carries its own plain-language guidance (retry hint for
              transient; "not available yet" for no-minter), so no secondary jargon line is shown. */}
          <Text style={S.err}>{err ?? 'No deposit address available.'}</Text>
        </View>
      ) : mintedTotal != null ? (
        <View style={S.centerAll}>
          <View style={S.check}><IconCheck size={44} color={C.brandInk}/></View>
          <Text style={S.paidText}>Deposited ✓</Text>
          <Text style={S.paidSub}>{fmtAsset(mintedTotal, display.amountDecimals, display.nativeAsset)} minted</Text>
          <Text style={S.dim2}>Your balance updates automatically.</Text>
          <Pressable testID="btn-deposit-done" style={[S.ghostBtn, S.ghostBtnMuted]} onPress={onClose} accessibilityRole="button" accessibilityLabel="Done" accessibilityState={{disabled: false}}><Text style={S.ghostBtnText}>Done</Text></Pressable>
        </View>
      ) : (
        <>
          {/* Complete, scannable instructions: network + asset + est. time + fee + min + the
              one-line non-custody reassurance. All values come from `deposit_info` (never
              hardcoded); the network/asset are the family's config (FAMILY_DISPLAY). */}
          <View testID="deposit-instructions" style={S.instrCard}>
            <Text style={S.instrLine}>
              Send <Text style={S.instrAsset}>{display.nativeAsset}</Text> to your{' '}
              <Text style={S.instrAsset}>{display.networkLabel}</Text> address below.
            </Text>
            <Text style={S.instrMeta}>
              {required > 0 ? `~${required} confirmation${required === 1 ? '' : 's'}` : 'confirmations'}
              {estMin > 0 ? ` · typically ~${estMin} min` : ''}
            </Text>
            <Text style={S.instrMeta}>{`Network fee ${feeVal} · Min deposit ${minVal}`}</Text>
            <Text style={S.instrCustody}>
              dpay never holds your keys — funds mint 1:1 to your wallet on confirmation.
            </Text>
          </View>

          <View testID="deposit-qr" style={S.qrCard}><QrCode value={address} size={QR_SIZE_SMALL} ecl="L" /></View>

          <Text testID="deposit-address" style={S.sheetAddr} selectable={true}>{address}</Text>

          <Pressable
            testID="btn-deposit-copy"
            accessibilityRole="button"
            accessibilityLabel={copied === 'clipboard' ? 'Address copied' : copied === 'shared' ? 'Address shared' : 'Copy deposit address'}
            style={[S.primaryWide, S.depositCopy]}
            onPress={copy}>
            <IconCopy size={18} color={C.brandInk}/>
            <Text style={S.primaryText}>{copied === 'clipboard' ? 'Copied ✓' : copied === 'shared' ? 'Shared ✓' : 'Copy address'}</Text>
          </Pressable>

          {/* ONE single linear progress cue (no dual zero-state): the honest balance-watching
              message (the facade-subaccount per-UTXO progress died with custody — the minter's
              UTXO view is not readable at the user principal). The manual "Check now" button
              nudges the ledger recheck instead of relying solely on the 10s interval. */}
          <View testID="deposit-status" style={S.depositStatus}>
            <Text style={S.depositStatusTitle}>Status</Text>
            <Text style={S.depositStatusMain}>Watching for your deposit</Text>
            <Text style={S.depositStatusRow}>{`checking every ${POLL.deposit / 1000}s`}</Text>
          </View>

          <Pressable
            testID="btn-deposit-check"
            accessibilityRole="button"
            accessibilityLabel="Check deposit status now"
            accessibilityState={{disabled: checkBusy}}
            style={[S.checkBtn, checkBusy && S.dim]}
            disabled={checkBusy}
            onPress={() => refreshNow(true)}>
            {checkBusy
              ? <ActivityIndicator size="small" color={C.brand} />
              : <Text style={S.checkBtnText}>Check now</Text>}
          </Pressable>

          {Platform.OS === 'web' ? <Text style={S.dim2}>Press Esc to close</Text> : null}
        </>
      )}
    </>
  );

  return <View style={S.sheetBody}>{body}</View>;
}
