/**
 * ckBTC-style deposit sheet (IC user-principal rail). The deposit address is generated by the
 * ckBTC minter's get_btc_address for THIS user's own principal (owner = self_authenticating(device
 * pubkey)) — a signed UPDATE straight to /api/v2 (the real minter exposes get_btc_address as an
 * update method only; its request_status is polled like any rail update), no relay, no facade
 * subaccount. Mint detection is an honest balance recheck: poll icrc1_balance_of on the ledger
 * and compare against the baseline captured at first successful read (the facade-subaccount
 * pending-UTXO progress cue is gone — the minter's per-UTXO view lived behind facade custody).
 * Fee/min/confirmations still come from the relay's read-only /deposit/info (display-only
 * network facts).
 */
export function DepositSheet({identity, relayUrl, catalog, currency, display, funding, onClose}: {identity: Identity; relayUrl: string; catalog: CurrencyDescriptor[]; currency: number; display: FamilyDisplay; funding?: ReactNode; onClose: () => void}) {
  /** The minter's deposit-address read produced no fact. The blame is CLASSIFIED (the shared
   *  oracle — the SOL head is off the IC path this read failed on), never a flat "check your
   *  connection" while the phone is online (work order 2026-09-30). Nothing is at risk either
   *  way: no funds move toward an address the wallet never showed. */
  async function addressFetchErr(): Promise<string> {
    return (await classifyIcReadFailure()) === 'offline'
      ? M.deposit.ck.addressOffline
      : M.deposit.ck.addressUnreachable;
  }
  const [info, setInfo] = useState<DepositInfo | null>(null);
  const [address, setAddress] = useState<string | null>(null);
  const [mintedTotal, setMintedTotal] = useState<string | null>(null);
  // Balance baseline (captured at the first successful ledger read while the sheet is open).
  // minted = current balance strictly ABOVE the baseline → the mint landed while watching.
  const baselineRef = useRef<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [err, setErr] = useState<string | null>(null);
  const {copied, copy: doCopy} = useCopyFeedback();
  // Manual "Check now": debounced + disabled while a refresh is in-flight (reuses the poll's fetch).
  const [checkBusy, setCheckBusy] = useState(false);

  const desc = catalog.find(c => c.currency === currency) ?? null;

  // Same-ledger receive route (founder 2026-08-29): anyone already holding ckBTC ON the IC can
  // plain-transfer it to this user's principal — no Bitcoin hop, no minter wait. Best-effort
  // local derivation; the section simply omits the address line if it fails.
  const [icPrincipal, setIcPrincipal] = useState<string | null>(null);
  useEffect(() => {
    let alive = true;
    DpayCore.icpSelfPrincipal(identity.secretHex)
      .then(p => { if (alive) setIcPrincipal(p); })
      // Omitting the section is the graceful part; omitting the reason is not. Matches the same
      // derivation's other two call sites (ReceiveMode, CkErc20DepositSheet).
      .catch((e: unknown) => { console.warn('icpSelfPrincipal failed (no same-ledger receive section):', e instanceof Error ? e.message : String(e)); });
    return () => { alive = false; };
  }, [identity.secretHex]);

  // Escape closes the sheet (seed of the keyboard-shortcuts surface — plan flow 14).
  useEscapeToClose(onClose);

  // The deposit ADDRESS is the critical path (it's the thing the user came for); deposit INFO
  // (fee/min/confirmations) is supplementary. They are fetched on SEPARATE controllers so the slow
  // relay info proxy can never abort the address (a signed update + poll, typically ~5–7s on
  // mainnet). The sheet tolerates a null `info` (renders "none"/"no minimum" for fee/min), so a
  // best-effort info miss degrades gracefully instead of hiding the address.
  useEffect(() => {
    let alive = true;
    const {signal, cancel} = withTimeout(DEPOSIT_ADDRESS_TIMEOUT_MS);
    (async () => {
      setLoading(true); setErr(null);
      try {
        const minter = desc?.minter ?? null;
        // H5: no minter registered for this currency → the asset has no deposit rail configured.
        if (!minter) { if (alive) setErr(M.deposit.ck.noMinter); return; }
        // Signed query at THIS user's principal — the minter accepts arbitrary owners (proven in
        // mock); the address pays out to Account{owner: user principal}, never facade custody.
        const a = await railBtcDepositAddress(identity.secretHex, minter, signal);
        if (!alive) return;
        if (!a) { setErr(await addressFetchErr()); return; } // no fact — blame classified below
        setAddress(a);
      } catch (e: unknown) {
        // The address IS this sheet. Swallowing the reason left one generic line on screen and
        // nothing at all in logcat, so a timeout, a rejected update and an unreachable boundary all
        // looked identical while a user waited for somewhere to send real funds. Same contract as
        // the info + balance catches below.
        console.warn('deposit address fetch failed:', e instanceof Error ? e.message : String(e));
        if (alive) setErr(await addressFetchErr());
      } finally {
        if (alive) setLoading(false);
        cancel();
      }
    })();
    return () => { alive = false; };
  }, [identity.secretHex, desc]);

  // Best-effort deposit info (fee / min / confirmations). Independent controller + timeout so a slow
  // or failing info fetch never blocks the address above. `info` stays null on a miss → the sheet
  // renders "none"/"no minimum" for the fee/min fields (graceful, not an error).
  useEffect(() => {
    let alive = true;
    // The caller timer sits 1 s STRICTLY AFTER the 20 s grant (DEPOSIT_TIMEOUT_MS — also the armed
    // walk's attempt-0 deadline when a second relay exists): at a tied 20000/20000 the caller timer,
    // armed first, wins and a hung primary reads as a CALLER decision — no cooldown, no failover.
    // Same +1000 classification margin as useBalancePoll; the walk keeps the full 20 s grant.
    const {signal, cancel} = withTimeout(DEPOSIT_TIMEOUT_MS + 1000);
    (async () => {
      try {
        const i = await depositInfo(relayUrl, currency, signal);
        if (alive) setInfo(i);
      } catch (e) { console.warn('depositInfo fetch failed: ', e); }
      finally { cancel(); }
    })();
    return () => { alive = false; };
  }, [relayUrl, currency]);

  // ONE refresh function reused by BOTH the 10s poll and the manual "Check now" button — single
  // source of truth. Honest mint detection: signed icrc1_balance_of against the ledger; the first
  // successful read is the baseline, any strictly-higher later read = the mint landed (delta shown).
  const refreshNow = useCallback(async (manual: boolean) => {
    if (manual) {
      setCheckBusy(true);
    }
    try {
      const ledger = desc?.ledger ?? '';
      if (!ledger) return;
      const bal = await railBalanceOf(identity.secretHex, ledger);
      if (bal != null) {
        const base = baselineRef.current;
        if (base == null) {
          baselineRef.current = bal; // first successful read while open — the watching baseline
        } else if (cmpRaw(bal, base) > 0) {
          // MC1: raw-u64 decimal STRINGS; the delta via BigInt (both are digit strings).
          setMintedTotal((BigInt(bal) - BigInt(base)).toString());
        }
      }
    } catch (e) { console.warn('deposit balance recheck failed: ', e); }
    finally {
      if (manual) {
        setCheckBusy(false);
      }
    }
  }, [identity.secretHex, desc]);

  // Poll every POLL.deposit while open; cleans up on close.
  useEffect(() => {
    let alive = true;
    const poll = () => { if (alive) { refreshNow(false); } };
    poll(); const id = setInterval(poll, POLL.deposit);
    return () => { alive = false; clearInterval(id); };
  }, [refreshNow]);

  const copy = useCallback(async () => {
    if (address) { await doCopy(address); }
  }, [address, doCopy]);

  const required = info?.min_confirmations ?? 0;
  const estMin = required > 0 ? required * display.blockMin : 0;
  // C3: never render a raw "0.00000000 BTC" — when a fee/min value is zero (the test minter /
  // FakeLedger returns zeros; a future no-fee asset) show an explicit word for that part and format
  // normally only when non-zero. The labels stay so the fields remain visible; only the bogus zero
  // amount (8 trailing zeros) is suppressed — a premium app never shows that to a user. The word
  // (vs a bare "—") keeps the field from reading as "broken/loading" on a money screen: see
  // M.deposit.ck.feeNone / .minNone. MC1 units 2-4: fee/min are raw-u64 decimal STRINGS;
  // zero-presence via `cmpRaw` (BigInt) — never `> 0`.
  const feeVal = info && cmpRaw(info.deposit_fee, '0') > 0 ? fmtAssetCompact(info.deposit_fee, display.amountDecimals, display.nativeAsset) : M.deposit.ck.feeNone;
  const minVal = info && info.deposit_min_amount != null && cmpRaw(info.deposit_min_amount, '0') > 0 ? fmtAssetCompact(info.deposit_min_amount, display.amountDecimals, display.nativeAsset) : M.deposit.ck.minNone;

  // The body content is rendered inline in the Receive tab's "My address" sub-mode (the tab body
  // already provides the scroll surface + the overlay chrome). `onClose` is wired to the inner
  // "Done" buttons so a completed/esc flow returns to the request sub-mode.
  const body = (
    <>
      {loading ? (
        <View style={S.centerAll}>
          <ActivityIndicator color={C.brandText} />
          <Text style={S.dim2}>{M.deposit.ck.fetchingAddress}</Text>
        </View>
      ) : err || !address ? (
        <View style={S.centerAll}>
          {/* H5: the message already carries its own plain-language guidance (retry hint for
              transient; "not available yet" for no-minter), so no secondary jargon line is shown. */}
          <Text style={S.err}>{err ?? M.deposit.ck.noAddress}</Text>
        </View>
      ) : mintedTotal != null ? (
        <View style={S.centerAll}>
          <View style={S.check}><IconCheck size={44} color={C.brandInk}/></View>
          <Text style={S.paidText}>{M.deposit.deposited}</Text>
          <Text style={S.paidSub}>{M.deposit.ck.mintedAmount(fmtAssetCompact(mintedTotal, display.amountDecimals, display.nativeAsset))}</Text>
          <Text style={S.dim2}>{M.deposit.balanceAuto}</Text>
          <Pressable testID="btn-deposit-done" style={[S.ghostBtn, S.ghostBtnMuted]} onPress={onClose} accessibilityRole="button" accessibilityLabel={M.common.done} accessibilityState={{disabled: false}}><Text style={S.ghostBtnText}>{M.common.done}</Text></Pressable>
        </View>
      ) : (
        <>
          {/* Complete, scannable instructions: network + asset + est. time + fee + min.
              All values come from `deposit_info` (never hardcoded); the network/asset are the
              family's config (FAMILY_DISPLAY). The custody reassurance went with the 10x
              verbosity pass (2026-09-17): it is stated at onboarding and in Settings and
              changed no decision here. */}
          <View testID="deposit-instructions" style={S.instrCard}>
            <InstrLine runs={M.deposit.ck.sendToAddress(display.nativeAsset, display.networkLabel)} />
            <Text style={S.instrMeta}>{M.deposit.ck.confirmationLine(required, estMin)}</Text>
            <Text style={S.instrMeta}>{M.deposit.ck.feeMinLine(feeVal, minVal)}</Text>
          </View>

          <View testID="deposit-qr" style={S.qrCard}><QrCode value={address} size={QR_SIZE_SMALL} ecl="L" /></View>

          <Text testID="deposit-address" style={S.sheetAddr} selectable={true}>{address}</Text>

          <Pressable
            testID="btn-deposit-copy"
            accessibilityRole="button"
            accessibilityLabel={copied === 'clipboard' ? M.deposit.addressCopied : copied === 'shared' ? M.deposit.addressShared : M.deposit.ck.copyDepositAddress}
            style={[S.primaryWide, S.depositCopy]}
            onPress={copy}>
            <IconCopy size={18} color={C.brandInk}/>
            <Text style={S.primaryText}>{copied === 'clipboard' ? M.deposit.copied : copied === 'shared' ? M.deposit.shared : M.deposit.copyAddress}</Text>
          </Pressable>

          {/* Trust Wallet send deep link (2026-08-17 plan): one-tap funding for Trust holders —
              MAINNET BTC only (testnet ckBTC has no Trust asset id → copy/QR status quo;
              ckERC20 assets keep the WalletConnect path — the link's data param is unusable
              for calldata). Rendered in the same slot on SolanaReceiveSheet (same-surfaces). */}
          {isTrustWalletFundableBtc(desc) ? <TrustWalletFundButton asset="BTC" address={address} /> : null}

          {/* Secondary route: the ckBTC ICRC-1 account (the watch above detects a plain transfer
              the same as a mint). Kept below the BTC address — the primary for external funds. */}
          <IcrcAccountSection symbol={desc?.wrapper_name ?? desc?.symbol ?? ''} principal={icPrincipal} />

          {/* ONE single linear progress cue (no dual zero-state): the honest balance-watching
              message (the facade-subaccount per-UTXO progress died with custody — the minter's
              UTXO view is not readable at the user principal). The manual "Check now" button
              nudges the ledger recheck instead of relying solely on the 10s interval. */}
          <View testID="deposit-status" style={S.depositStatus}>
            <Text style={S.depositStatusTitle}>{M.deposit.ck.statusTitle}</Text>
            <Text style={S.depositStatusMain}>{M.deposit.ck.watching}</Text>
            <Text style={S.depositStatusRow}>{M.deposit.ck.checkingEvery(POLL.deposit / 1000)}</Text>
          </View>

          <Pressable
            testID="btn-deposit-check"
            accessibilityRole="button"
            accessibilityLabel={M.deposit.ck.checkNowLabel}
            accessibilityState={{disabled: checkBusy}}
            style={[S.checkBtn, checkBusy && S.dim]}
            disabled={checkBusy}
            onPress={() => refreshNow(true)}>
            {checkBusy
              ? <ActivityIndicator size="small" color={C.brandText} />
              : <Text style={S.checkBtnText}>{M.deposit.checkNow}</Text>}
          </Pressable>

          {/* The step BEFORE the address: this sheet shows a real Bitcoin address and says nothing
              about where a traveller gets Bitcoin. Built by the caller (see IcrcDepositSheet's note
              on why), placed here — below the address, and never over the minted state. */}
          {funding}

          {Platform.OS === 'web' ? <Text style={S.dim2}>{M.deposit.pressEsc}</Text> : null}
        </>
      )}
    </>
  );

  return <View style={S.sheetBody}>{body}</View>;
}
