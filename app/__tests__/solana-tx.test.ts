    const ix = buildSolTransferInstruction(FROM_BYTES, TO_BYTES, LAMPORTS);
    expect(ix.keys).toHaveLength(2);
    expect(ix.keys[0]).toEqual({pubkey: FROM_BYTES, signer: true, writable: true});
