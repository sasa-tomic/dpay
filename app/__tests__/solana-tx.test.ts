function toHex(bytes: Uint8Array): string {
  return Array.from(bytes)
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

function hexToBytes(hex: string): Uint8Array {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}

describe('solana/tx — compact-u16 varint', () => {
  test('encodes small values as a single byte', () => {
    const out: number[] = [];
    encodeCompactU16(out, 3);
    expect(out).toEqual([3]);
    encodeCompactU16(out, 127);
    expect(out).toEqual([3, 127]);
  });

  test('encodes >=128 with continuation bit', () => {
    const out: number[] = [];
    encodeCompactU16(out, 128);
    expect(out).toEqual([0x80, 0x01]);
    const out2: number[] = [];
    encodeCompactU16(out2, 300);
    expect(out2).toEqual([0xac, 0x02]);
  });
});

