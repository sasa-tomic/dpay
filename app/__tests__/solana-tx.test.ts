/** Build the {Memo, System.transfer} instruction list for arbitrary request — used by extra-ix and
 *  reorder mutation tests that need the individual instructions rather than the assembled message. */
function buildSolInstructions(payer: Uint8Array, req: SolReqV2): Instruction[] {
  const uri = encodeSolReq(req);
  const memoIx = buildMemoInstruction(solreqMemoData(uri));
  const transferData: number[] = [];
  encodeU32LE(transferData, 2);
  encodeU64LE(transferData, BigInt(req.amt));
  const transferIx: Instruction = {
    programId: SYSTEM_PROGRAM_BYTES,
    keys: [
      { pubkey: payer, signer: true, writable: true },
      { pubkey: base58Decode32(req.to), signer: false, writable: true },
    ],
    data: new Uint8Array(transferData),
  };
  return [memoIx, transferIx];
}

