    expect(ix.keys[2]).toEqual({pubkey: base58Decode32(REFERENCE), signer: false, writable: false});
    expect(ix.keys[3]).toEqual({pubkey: base58Decode32(SECOND_REFERENCE), signer: false, writable: false});
