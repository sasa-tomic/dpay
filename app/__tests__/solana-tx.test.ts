// ============================================================================
// Legacy signed-tx parser primitives — the foundation verifySolPayment (below) builds on. The
// merchant path extracts the fee-payer signature + message from the raw signed tx bytes. The parse
// is PURE + TOTAL — a malformed tx returns null, never throws.
// ============================================================================
describe('decodeCompactU16 — varint decoder (inverse of encodeCompactU16)', () => {
  test('decodes single-byte values', () => {
    expect(decodeCompactU16(new Uint8Array([3]), 0)).toEqual({value: 3, next: 1});
    expect(decodeCompactU16(new Uint8Array([127]), 0)).toEqual({value: 127, next: 1});
  });

  test('decodes multi-byte values with the continuation bit', () => {
    expect(decodeCompactU16(new Uint8Array([0x80, 0x01]), 0)).toEqual({value: 128, next: 2});
    expect(decodeCompactU16(new Uint8Array([0xac, 0x02]), 0)).toEqual({value: 300, next: 2});
  });

  test('reads from a non-zero offset (the account-table count sits after the 3-byte header)', () => {
    const msg = new Uint8Array([1, 0, 1, 0x03]);
    expect(decodeCompactU16(msg, 3)).toEqual({value: 3, next: 4});
  });
});

describe('extractSignedTxParts — legacy signed-tx layout parse', () => {
  test('extracts the signature, message, and fee-payer pubkey from a real signed tx', () => {
    const kp = deriveSolanaKeypair(SEED_HEX);
    const wire = buildSignedTransfer(kp.seed, kp.publicKey, TO_ADDRESS, LAMPORTS, BLOCKHASH_ZEROS);
    const parts = extractSignedTxParts(wire);
    expect(parts).not.toBeNull();
    expect(parts!.signature.length).toBe(64);
    // account[0] in the golden message is the from-payer pubkey (28b3...).
    expect(toHex(parts!.feePayer)).toBe(FROM_PUBKEY_HEX);
  });

  test('returns null on a too-short tx (no room for a header)', () => {
    expect(extractSignedTxParts(new Uint8Array([0x01, 0x02, 0x03]))).toBeNull();
  });

  test('returns null on a zero-signature count', () => {
    expect(extractSignedTxParts(new Uint8Array([0x00]))).toBeNull();
  });

  test('returns null (no throw) on garbage bytes — the e2e harness carries placeholder tx bytes', () => {
    const dummy = new Uint8Array(Array.from('dummy-signed-tx-bytes').map(c => c.charCodeAt(0)));
    expect(extractSignedTxParts(dummy)).toBeNull();
  });
});

