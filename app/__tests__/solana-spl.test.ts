describe('Phase 2 — verifySolPayment USDC happy + mutations', () => {
  test('accepts the golden signed USDC tx against the golden message', () => {
    const result = verifySolPayment(USDC_MESSAGE, { tx: USDC_SIGNED_TX });
    expect(result).toEqual({ ok: true, payer: V2_PAYER_ADDRESS, signature: expect.any(String) });
    if (result.ok) {
      expect(result.payer).toBe(V2_PAYER_ADDRESS);
      expect(result.signature.length).toBeGreaterThan(0);
    }
  });

  test('rejects a changed mint (→ message-mismatch)', () => {
    const mutatedReq = { ...USDC_REQ, mint: '11111111111111111111111111111112' } as SolReqV2;
    const expectedMutated = buildCanonicalUsdcMessage(USDC_PAYER, mutatedReq);
    expect(verifySolPayment(expectedMutated, { tx: USDC_SIGNED_TX })).toEqual({ ok: false, reason: 'message-mismatch' });
  });

  test('rejects a changed destination ATA (→ message-mismatch)', () => {
    const mutatedReq = { ...USDC_REQ, toAta: SOURCE_ATA } as SolReqV2;
    const expectedMutated = buildCanonicalUsdcMessage(USDC_PAYER, mutatedReq);
    expect(verifySolPayment(expectedMutated, { tx: USDC_SIGNED_TX })).toEqual({ ok: false, reason: 'message-mismatch' });
  });

  test('rejects a changed amount (→ message-mismatch)', () => {
    const mutatedReq = { ...USDC_REQ, amt: '999999' } as SolReqV2;
    const expectedMutated = buildCanonicalUsdcMessage(USDC_PAYER, mutatedReq);
    expect(verifySolPayment(expectedMutated, { tx: USDC_SIGNED_TX })).toEqual({ ok: false, reason: 'message-mismatch' });
  });

  test('rejects a changed source ATA via different payer (→ message-mismatch)', () => {
    const otherKp = deriveSolanaKeypair('bb'.repeat(32));
    const otherMsg = buildCanonicalUsdcMessage(otherKp.publicKey, USDC_REQ);
    const otherTx = signTransaction(otherMsg, otherKp.seed);
    expect(verifySolPayment(USDC_MESSAGE, { tx: otherTx })).toEqual({ ok: false, reason: 'message-mismatch' });
  });

  test('rejects decimals=5 in the transferChecked ix (→ message-mismatch)', () => {
    const uri = encodeSolReq(USDC_REQ);
    const memoIx = buildMemoInstruction(solreqMemoData(uri));
    const sourceAta = deriveAta(bs58.encode(USDC_PAYER), USDC_REQ.mint!);
    const transferIx = buildTransferCheckedInstruction(
      sourceAta,
      base58Decode32(USDC_REQ.mint!),
      base58Decode32(USDC_REQ.toAta!),
      USDC_PAYER,
      BigInt(USDC_REQ.amt),
      5,
    );
    const msg = assembleMessage(USDC_PAYER, [memoIx, transferIx], base58Decode32(USDC_REQ.bh));
    const tx = signTransaction(msg, USDC_KP.seed);
    expect(verifySolPayment(USDC_MESSAGE, { tx })).toEqual({ ok: false, reason: 'message-mismatch' });
  });
});
