/**
 * dpay — offline-pay / online-confirm, on a real phone.
 *
 * Every money operation here calls the shared Rust core (dpay-core) through the DpayCore native
 * module, which delegates to the UniFFI-generated Kotlin binding + the NDK-built libdpay_ffi.so.
 * The phone signs with byte-for-byte the same code the canister, relay, sim, and Claude's headless
 * tests use — no reimplementation in JS.
 */
import React, {useEffect, useState} from 'react';
import {
  SafeAreaView,
  ScrollView,
  StatusBar,
  View,
  Text,
  Pressable,
  TextInput,
  StyleSheet,
  NativeModules,
} from 'react-native';

const {DpayCore} = NativeModules as {DpayCore: DpayCoreApi};

type DpayCoreApi = {
  generateKeypair(): Promise<{secretHex: string; publicHex: string}>;
  signAuthorization(
    secretHex: string,
    toHex: string,
    amount: number,
    nonceHex: string,
    expiry: number,
  ): Promise<string>;
  encodeQr(wireHex: string): Promise<string>;
  verifyWire(wireHex: string): Promise<boolean>;
  validate(
    amount: number,
    now: number,
    expiry: number,
    cap: number,
    balance: number,
    nonceSeen: boolean,
    sigOk: boolean,
  ): Promise<string | null>;
};

const C = {
  bg: '#ffffff',
  ink: '#0b0b0f',
  sub: '#6b7280',
  brand: '#4f46e5',
  brandInk: '#ffffff',
  ok: '#16a34a',
  line: '#e5e7eb',
  field: '#f3f4f6',
};

// Deterministic demo merchant (== account_b in the dfx-deployed ledger).
const MERCHANT_HEX =
  '8139770ea87d175f56a35466c34c7ecccb8d8a91b4ee37a25df60f5b8fc9b394';
const MERCHANT_NAME = 'Café Demo';
const CAP = 100000; // $1,000.00 per-tx cap (matches the canister)
const EXPIRY = 4102444800; // 2100-01-01Z

function toCents(s: string): number {
  const n = Math.round(parseFloat(s || '0') * 100);
  return Number.isFinite(n) && n > 0 ? n : 0;
}
function usd(cents: number): string {
  return `$${Math.floor(cents / 100)}.${String(cents % 100).padStart(2, '0')}`;
}
function randNonceHex(): string {
  let s = '';
  for (let i = 0; i < 16; i++) {
    s += Math.floor(Math.random() * 256).toString(16).padStart(2, '0');
  }
  return s;
}

export default function App() {
  const [tab, setTab] = useState<'receive' | 'pay'>('pay');
  const [account, setAccount] = useState<{secretHex: string; publicHex: string} | null>(null);
  const [err, setErr] = useState<string | null>(null);

  useEffect(() => {
    // Onboarding: one on-device Ed25519 key, generated by the Rust core's native CSPRNG.
    DpayCore.generateKeypair()
      .then(setAccount)
      .catch(e => setErr(String(e?.message ?? e)));
  }, []);

  // Autonomous on-device self-check: exercise the real core end-to-end and log a marker to logcat,
  // so the run harness can assert the running app truly invoked dpay-core (independent of UI taps).
  useEffect(() => {
    if (!account) return;
    (async () => {
      try {
        const nonce = '2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a';
        const wire = await DpayCore.signAuthorization(account.secretHex, MERCHANT_HEX, 2500, nonce, EXPIRY);
        const verify = await DpayCore.verifyWire(wire);
        const expired = await DpayCore.validate(2500, 5000000000, EXPIRY, CAP, 10000, false, true);
        const pass = verify && expired === 'expired' && wire.length === 384;
        console.log(`DPAY_SELFCHECK ${pass ? 'PASS' : 'FAIL'} wireLen=${wire.length / 2} verify=${verify} expiredRule=${expired}`);
      } catch (e: any) {
        console.log(`DPAY_SELFCHECK FAIL ${String(e?.message ?? e)}`);
      }
    })();
  }, [account]);

  return (
    <SafeAreaView style={S.root}>
      <StatusBar barStyle="dark-content" backgroundColor={C.bg} />
      <View style={S.header}>
        <Text style={S.brand}>dpay</Text>
        <Text style={S.role}>{tab === 'pay' ? 'Pay' : 'Receive'}</Text>
      </View>

      <View style={S.tabs}>
        <Tab label="Pay" active={tab === 'pay'} onPress={() => setTab('pay')} />
        <Tab label="Receive" active={tab === 'receive'} onPress={() => setTab('receive')} />
      </View>

      <ScrollView contentContainerStyle={S.body} keyboardShouldPersistTaps="handled">
        {err ? (
          <Text testID="err" style={S.err}>{`core error: ${err}`}</Text>
        ) : !account ? (
          <Text style={S.dim}>starting secure core…</Text>
        ) : tab === 'pay' ? (
          <PayScreen account={account} onError={setErr} />
        ) : (
          <ReceiveScreen />
        )}
      </ScrollView>

      {account ? (
        <Text testID="acct" style={S.acct}>{`account ${account.publicHex.slice(0, 10)}… · key by dpay-core`}</Text>
      ) : null}
    </SafeAreaView>
  );
}

function Tab({label, active, onPress}: {label: string; active: boolean; onPress: () => void}) {
  return (
    <Pressable onPress={onPress} style={[S.tab, active && S.tabActive]} testID={`tab-${label.toLowerCase()}`}>
      <Text style={[S.tabText, active && S.tabTextActive]}>{label}</Text>
    </Pressable>
  );
}

function PayScreen({
  account,
  onError,
}: {
  account: {secretHex: string; publicHex: string};
  onError: (s: string) => void;
}) {
  const [scan, setScan] = useState<{cents: number} | null>(null);
  const [result, setResult] = useState<{qr: string; verified: boolean; cents: number} | null>(null);
  const [busy, setBusy] = useState(false);

  async function approve() {
    if (!scan) return;
    setBusy(true);
    try {
      const nonce = randNonceHex();
      // 1. sign the authorization OFFLINE, in Rust, on the device
      const wireHex = await DpayCore.signAuthorization(
        account.secretHex,
        MERCHANT_HEX,
        scan.cents,
        nonce,
        EXPIRY,
      );
      // 2. the same core verifies it (what the merchant/relay/canister will re-check)
      const verified = await DpayCore.verifyWire(wireHex);
      // 3. the compact QR the merchant would scan
      const qr = await DpayCore.encodeQr(wireHex);
      setResult({qr, verified, cents: scan.cents});
    } catch (e: any) {
      onError(String(e?.message ?? e));
    } finally {
      setBusy(false);
    }
  }

  if (result) {
    return (
      <View style={S.center}>
        <View style={S.check}><Text style={S.checkMark}>✓</Text></View>
        <Text testID="pay-paid" style={S.paid}>{`Paid ✓ ${usd(result.cents)}`}</Text>
        <Text style={S.paidSub}>{`to ${MERCHANT_NAME}`}</Text>
        <View style={S.badgeRow}>
          <Text style={[S.badge, result.verified ? S.badgeOk : S.badgeBad]}>
            {result.verified ? 'signed offline · verified on-device' : 'signature INVALID'}
          </Text>
        </View>
        <Text style={S.mono} testID="pay-qr">{`auth ${result.qr.slice(0, 22)}…`}</Text>
        <Pressable style={S.linkBtn} onPress={() => { setResult(null); setScan(null); }}>
          <Text style={S.linkText}>New payment</Text>
        </Pressable>
      </View>
    );
  }

  if (!scan) {
    return (
      <View style={S.center}>
        <View style={S.scanFrame} />
        <Text style={S.dim}>Scan a request to pay…</Text>
        <Pressable
          testID="btn-scan"
          style={S.primary}
          onPress={() => setScan({cents: 2500})}>
          <Text style={S.primaryText}>Simulate scan · $25.00</Text>
        </Pressable>
      </View>
    );
  }

  return (
    <View style={S.center}>
      <Text style={S.reviewLabel}>Review payment</Text>
      <Text testID="pay-amount" style={S.reviewAmount}>{`Pay ${usd(scan.cents)} to ${MERCHANT_NAME}`}</Text>
      <Pressable testID="btn-approve" style={[S.primary, busy && S.primaryDim]} disabled={busy} onPress={approve}>
        <Text style={S.primaryText}>{busy ? 'Signing…' : 'Approve'}</Text>
      </Pressable>
      <Text style={S.dim}>signs offline · airplane mode OK</Text>
    </View>
  );
}

function ReceiveScreen() {
  const [amount, setAmount] = useState('25.00');
  const [requested, setRequested] = useState(false);
  return (
    <View>
      <Text style={S.label}>Amount to charge</Text>
      <View style={S.amountRow}>
        <Text style={S.currency}>$</Text>
        <TextInput
          testID="amount-input"
          style={S.amountInput}
          value={amount}
          onChangeText={setAmount}
          keyboardType="decimal-pad"
          placeholder="0.00"
        />
      </View>
      {!requested ? (
        <Pressable testID="btn-request" style={S.primaryWide} onPress={() => setRequested(true)}>
          <Text style={S.primaryText}>Request</Text>
        </Pressable>
      ) : (
        <View style={S.center}>
          <View style={S.qrPlaceholder}><Text style={S.qrGlyph}>▚▞▚</Text></View>
          <Text style={S.reviewAmount}>{`Charge $${amount}`}</Text>
          <Text style={S.dim}>Show this to the payer</Text>
        </View>
      )}
    </View>
  );
}

