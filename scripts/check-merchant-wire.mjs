#!/usr/bin/env node
// Merchant-terminal wire parity assertion (the "can I pay the web terminal?" invariant).
//
// The merchant terminal's request encoder lives in an HTML asset with NO compile-time link to the
// Rust core: crates/dpay-relay/assets/merchant.html embeds a hand-rolled JS `encodeRequest`.
// The core's request format is FROZEN (dpay-core lib.rs, REQUEST_LEN=132,
// to(32)|amount(8)|nonce(16)|expiry(8)|currency(4)|to_name(32)|memo(32), wire v2). When the two
// drift (as happened 2026-07-31: the terminal still encoded the 68-byte v1 form), the app's
// decoder rejects the terminal's QR on scan — "can't pay from the app to the web terminal" — and
// every headless gate stays green because no e2e flow drives the REAL terminal page.
//
// This script is the static net: extract the terminal's `encodeRequest` from the served HTML,
// run it against the trusted byte-exact builder (e2e/harness/wire.mjs, which reads
// dfx/wire_layout.json generated by the Rust core itself), and assert byte-equality across a
// matrix of amounts/names/memos (incl. UTF-8 + truncation at 32 bytes). Sub-second, no server.
//
// Usage: node scripts/check-merchant-wire.mjs   (exit 0 = parity, exit 1 = drift)
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {buildRequestBytes, REQUEST_LEN} from '../e2e/harness/wire.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const HTML = `${ROOT}crates/dpay-relay/assets/merchant.html`;

const html = readFileSync(HTML, 'utf8');

// Extract the encoder helpers as a self-contained program: `hexToBytes` (first helper) through the
// end of `encodeRequest` (the `}` on the line after `return b64url(b);`). Anchored on stable
// markers; a reformat that moves them fails loud below rather than silently skipping the check.
const START = html.indexOf('function hexToBytes');
const RET = html.indexOf('return b64url(b);');
const endFn = html.indexOf('}', RET);
if (START < 0 || RET < 0 || endFn < 0) {
  console.error('FAIL: could not locate the encoder helpers/encodeRequest in merchant.html');
  process.exit(1);
}
const snippet = html.slice(START, endFn + 1);

// Run the terminal's code in a sandbox that provides the browser globals it uses.
const sandbox = {
  btoa: s => Buffer.from(s, 'binary').toString('base64'),
  TextEncoder,
  console,
};
const program = snippet + '\nreturn encodeRequest;';
const encodeRequestTerminal = new Function(...Object.keys(sandbox), program)(...Object.values(sandbox));

// Ground truth fields. `to` is any 32-byte key; the terminal pads names to 32 with NULs itself.
// Amounts/expiry pass as Numbers — the terminal's own convention (`Date.now()/1000+600`, cents);
// all test values stay under 2^53 so the u64 LE encodings are exact.
const TO = 'ab'.repeat(32);
const NONCE = 'cd'.repeat(16);
const EXPIRY = 0x11223344;

const cases = [
  {cents: 2500, toName: 'Café Demo'},
  {cents: 1, toName: 'A'},
  {cents: 4503599627370495, toName: 'ünïcödé nàme 漢字 ok?'}, // 2^52-1: max exact-integer stress
  {cents: 500, toName: 'x'.repeat(40)}, // longer than 32 → must truncate identically
];

let fail = 0;
for (const {cents, toName} of cases) {
  const terminalBytes = (() => {
    const b64 = encodeRequestTerminal(TO, cents, NONCE, EXPIRY, 0, toName);
    return Buffer.from(b64.replace(/-/g, '+').replace(/_/g, '/'), 'base64');
  })();
  const coreBytes = Buffer.from(buildRequestBytes(TO, BigInt(cents), NONCE, BigInt(EXPIRY), 0, toName, ''));
  const hex = b => b.toString('hex');
  const t = hex(terminalBytes), c = hex(coreBytes);
  const ok = t === c && terminalBytes.length === coreBytes.length && coreBytes.length === REQUEST_LEN;
  if (!ok) {
    fail++;
    console.error(`DRIFT (to_name=${JSON.stringify(toName)}):`);
    console.error(`  terminal: len=${terminalBytes.length} ${t.slice(0, 260)}…`);
    console.error(`  core:     len=${coreBytes.length} ${c.slice(0, 260)}…`);
  }
}

if (fail) {
  console.error(`\nFAIL: merchant.html request encoder drifted from dpay-core (REQUEST_LEN=132 wire v2) in ${fail} case(s).`);
  console.error('The app would refuse the terminal\'s QR. Fix merchant.html encodeRequest to match e2e/harness/wire.mjs.');
  process.exit(1);
}
console.log(`merchant-wire parity OK: terminal encodeRequest == dpay-core 132-byte request across ${cases.length} cases (incl. UTF-8 + 32-byte truncation)`);
