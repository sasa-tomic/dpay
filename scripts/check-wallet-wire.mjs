#!/usr/bin/env node
// Browser-wallet wire parity assertion (the "/wallet signs like the core" invariant).
//
// The browser wallet page (crates/dpay-relay/assets/wallet.html) binds to the SHARED wasm core:
// its guarded `wallet-wire-v2` block is a thin binding layer over crates/dpay-wasm (fetched at
// /dpay-core.wasm in prod) plus the JS BIP-39 codec. If the binding drifts (wrong lo/hi split,
// stale memory view, wrong claim layout, a stale receipt pin), every payment the web wallet signs
// is refused by the ledger — or worse, a RESTORED wallet derives a different key than the Android
// app and "the same 24 words" open a different account.
//
// This script extracts the guarded block between the `// >>> wallet-wire-v2` / `// <<< wallet-wire-v2`
// fences (stable markers: restyling the page never moves them), initializes it with a Node-
// instantiated copy of the STAGED crates/dpay-relay/assets/dpay-core.wasm (the EXACT artifact
// /dpay-core.wasm serves — the fence's initWalletWire takes an injected instance, the fetch path
// only runs in the browser), and asserts equality with the trusted builders in e2e/harness/
// wire.mjs (which read dfx/wire_layout.json generated by the Rust core itself, and whose
// signatures are cross-validated against ed25519-dalek in e2e test 00):
//   - buildRequestBytes  == core 132-byte request           (incl. UTF-8 names, 32-byte truncation)
//   - signAuthorization  == wire.mjs signAuthorizationCode  (same secretHex → same 292-byte wire QR)
//   - withdraw sig       == wire.mjs signWithdrawalHex      (same secretHex → same sig hex)
//   - receipt verify     == pinned-key true on a freshly signed claim / false on a flipped byte
//   - bip39 codec        == the canonical BIP-39 256-bit vectors (restore-compat with the app)
//   - static page facts  : CSP allows wasm, the page loads /dpay-core.wasm, no /ed25519.js remnant
// Sub-second, zero deps beyond node itself. Usage: node scripts/check-wallet-wire.mjs (0 = parity).
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as wire from '../e2e/harness/wire.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ASSETS = join(ROOT, 'crates/dpay-relay/assets');
const LAYOUT = JSON.parse(readFileSync(join(ROOT, 'dfx/wire_layout.json'), 'utf8'));

let fail = 0;
const bad = (msg) => { fail++; console.error(`DRIFT: ${msg}`); };

// --- 1. extract the guarded block from wallet.html (fail loud if the fence moved) -----------
const html = readFileSync(join(ASSETS, 'wallet.html'), 'utf8');
const OPEN = '// >>> wallet-wire-v2', CLOSE = '// <<< wallet-wire-v2';
const o = html.indexOf(OPEN), c = html.indexOf(CLOSE);
if (o < 0 || c < 0 || c < o) {
  console.error(`FAIL: could not locate the ${OPEN} … ${CLOSE} fence in wallet.html`);
  process.exit(1);
}
const fence = html.slice(o + OPEN.length, c);

// --- 1b. STATIC page asserts (the binding surface the byte checks can't see) ----------------
if (!html.includes("'wasm-unsafe-eval'")) bad("static: wallet.html CSP lacks 'wasm-unsafe-eval' — the browser will refuse to compile /dpay-core.wasm");
if (!html.includes('/dpay-core.wasm')) bad('static: wallet.html never references /dpay-core.wasm');
if (html.includes('/ed25519.js')) bad('static: wallet.html still references the removed /ed25519.js');
// The prod pin must STAY baked in the fence (single line + provenance comment, mirroring
// app/config/constants.ts EXPECTED_RECEIPT_PUBKEY).
const PROD_PIN = '83c5c568ea4c0a65e72531b8958ce4e9721f54c980b01e9f0047a67d6e18c4a8';
if (!fence.includes(PROD_PIN)) bad('static: the fence no longer bakes the prod facade receipt pin');

// --- 2. run the vendored noble-hashes + wordlist, then the fence with an injected core -------
// The vendored files are IIFEs assigning globalThis.<name>; passing a plain object as the shadowed
// `globalThis` parameter captures their exports without touching the real global. The fence runs
// with an ALREADY-INSTANTIATED copy of the STAGED dpay-core.wasm (the bytes /dpay-core.wasm
// serves) injected into initWalletWire — exactly the guard-injection seam the fence is designed
// for; its own fetch('/dpay-core.wasm') path only executes in the browser.
const sandbox = { crypto: globalThis.crypto };
for (const f of ['noble-hashes.js', 'wordlist.js']) {
  new Function('globalThis', readFileSync(join(ASSETS, f), 'utf8'))(sandbox);
}
if (!sandbox.nobleHashes || !sandbox.DPAY_WORDLIST) {
  console.error('FAIL: vendored noble-hashes/wordlist bundles did not export their globals');
  process.exit(1);
}
// Receipt-pin seam: set the SAME override the browser e2e sets (globalThis.__DPAY_TEST_RECEIPT_
// PUBKEY) BEFORE the fence evaluates, so PINNED_RECEIPT_PUBKEY binds a fixture key here exactly
// the way it binds the FakeLedger key in an e2e session. The fixture is wire_layout's own
// core-signed receipt golden keypair — its sig_hex was produced by the Rust core itself.
const ed = await import('../e2e/node_modules/@noble/ed25519/index.js');
const RG = LAYOUT.receipt.golden;
globalThis.__DPAY_TEST_RECEIPT_PUBKEY = RG.public_hex;
const stagedWasm = readFileSync(join(ASSETS, 'dpay-core.wasm'));
const coreInstance = (await WebAssembly.instantiate(stagedWasm, {})).instance;
const exports = new Function(
  'nobleHashes', 'DPAY_WORDLIST', 'crypto', 'TextEncoder', 'TextDecoder', 'console',
  fence + '\nreturn { PINNED_RECEIPT_PUBKEY, initWalletWire, buildRequestBytes, buildRequestQR, decodeRequest, signAuthorization, signWithdrawalHex, verifyReceipt, buildReceiptClaim, pubkeyHex, entropyToMnemonic, mnemonicToEntropy, validateMnemonic, stringToWords };',
)(sandbox.nobleHashes, sandbox.DPAY_WORDLIST, globalThis.crypto, TextEncoder, TextDecoder, console);
await exports.initWalletWire(coreInstance);
delete globalThis.__DPAY_TEST_RECEIPT_PUBKEY;
if (exports.PINNED_RECEIPT_PUBKEY !== RG.public_hex) bad(`pin seam failed: PINNED_RECEIPT_PUBKEY=${exports.PINNED_RECEIPT_PUBKEY}`);

const hex = b => Buffer.from(b).toString('hex');
const eqBytes = (a, b, what) => {
  const ha = hex(a), hb = hex(b);
  if (ha !== hb || a.length !== b.length) { bad(`${what}: page len=${a.length} core len=${b.length}\n  page: ${ha.slice(0, 200)}…\n  core: ${hb.slice(0, 200)}…`); return false; }
  return true;
};

// --- 3. request-encoder parity across the case matrix ---------------------------------------
const TO = 'ab'.repeat(32), NONCE = 'cd'.repeat(16);
const SECRET = LAYOUT.golden.secret_hex; // a fixed key so sigs are comparable case-to-case
const cases = [
  // The layout's two goldens use DIFFERENT memos: request_hex carries (Bob, coffee); wire_hex
  // (sig included) carries (Alice→Bob, dinner). Model them as separate cases, each pinned to its
  // own golden, plus adversarial shapes.
  { name: 'golden-request', to: LAYOUT.golden.to_hex, amount: 2500, nonce: LAYOUT.golden.nonce_hex, expiry: LAYOUT.golden.expiry, currency: 0, from: 'Alice', toName: 'Bob', memo: 'coffee', goldenReq: true },
  { name: 'golden-wire', to: LAYOUT.golden.to_hex, amount: 2500, nonce: LAYOUT.golden.nonce_hex, expiry: LAYOUT.golden.expiry, currency: 0, from: 'Alice', toName: 'Bob', memo: 'dinner', goldenWire: true },
  { name: 'utf8', to: TO, amount: 1, nonce: NONCE, expiry: 1234567890, currency: 1, from: 'ünïcödé nàme 漢字 ok?', toName: 'Café Demo', memo: 'grüß dich ✓' },
  { name: 'u64-2^52-1', to: TO, amount: 4503599627370495, nonce: NONCE, expiry: 1700000000, currency: 2, from: 'A', toName: 'B', memo: '' },
  { name: 'u64-2^63+', to: TO, amount: (2n ** 63n + 123456789n).toString(), nonce: NONCE, expiry: 1700000000, currency: 3, from: 'A', toName: 'B', memo: '' },
  { name: 'u64-max', to: TO, amount: '18446744073709551615', nonce: NONCE, expiry: 1, currency: 0, from: '', toName: '', memo: '' },
  { name: 'trunc-32', to: TO, amount: 500, nonce: NONCE, expiry: 1700000000, currency: 4294967295, from: 'x'.repeat(40), toName: 'y'.repeat(40), memo: 'z'.repeat(40) },
];
for (const tc of cases) {
  const pageReq = exports.buildRequestBytes(tc.to, tc.amount, tc.nonce, tc.expiry, tc.currency, tc.toName, tc.memo);
  const coreReq = wire.buildRequestBytes(tc.to, BigInt(tc.amount), tc.nonce, BigInt(tc.expiry), tc.currency, tc.toName, tc.memo);
  if (pageReq.length !== wire.REQUEST_LEN) bad(`request ${tc.name}: len ${pageReq.length} != ${wire.REQUEST_LEN}`);
  eqBytes(pageReq, coreReq, `request[${tc.name}] bytes`);
  if (tc.goldenReq) eqBytes(pageReq, Buffer.from(LAYOUT.golden.request_hex, 'hex'), 'golden request bytes');
  // decode round-trip (the Pay tab parses merchant QRs with this)
  const dec = exports.decodeRequest(exports.buildRequestQR(tc.to, tc.amount, tc.nonce, tc.expiry, tc.currency, tc.toName, tc.memo));
  const wantAmt = BigInt(tc.amount).toString();
  if (dec.toHex !== tc.to || dec.amount !== wantAmt || dec.nonceHex !== tc.nonce || dec.expiry !== BigInt(tc.expiry).toString()
    || dec.currency !== tc.currency || dec.toName !== tc.toName.slice(0, 32) || dec.memo !== tc.memo.slice(0, 32)) {
    bad(`decode[${tc.name}] round-trip: ${JSON.stringify(dec)}`);
  }
  // signing parity: same secretHex → byte-identical 292-byte wire QR (async core vs sync page)
  const pageQr = exports.signAuthorization(SECRET, tc.to, tc.amount, tc.nonce, tc.expiry, tc.currency, tc.from, tc.toName, tc.memo);
  const coreQr = await wire.signAuthorizationCode(SECRET, tc.to, BigInt(tc.amount), tc.nonce, BigInt(tc.expiry), tc.currency, tc.from, tc.toName, tc.memo);
  if (pageQr !== coreQr) bad(`sign[${tc.name}]: page wire QR != wire.mjs wire QR\n  page: ${pageQr.slice(0, 80)}…\n  core: ${coreQr.slice(0, 80)}…`);
  if (Buffer.from(wire.b64urlDecode(pageQr)).length !== wire.WIRE_LEN) bad(`sign[${tc.name}]: wire len != ${wire.WIRE_LEN}`);
  if (tc.goldenWire) {
    eqBytes(wire.b64urlDecode(pageQr), Buffer.from(LAYOUT.golden.wire_hex, 'hex'), 'golden 292-byte wire (sig included)');
  }
}

// --- 4. withdraw-sig parity (w_sign_withdraw; from is derived from the seed) -----------------
const WG = LAYOUT.withdraw.golden;
{
  const pageSig = exports.signWithdrawalHex(WG.secret_hex, WG.public_hex, WG.destination, WG.amount, WG.nonce_hex, WG.expiry, WG.currency);
  const coreSig = await wire.signWithdrawalHex(WG.secret_hex, WG.public_hex, WG.destination, WG.amount, WG.nonce_hex, WG.expiry, WG.currency);
  if (pageSig !== coreSig || pageSig !== WG.sig_hex) bad(`withdraw golden sig: page=${pageSig} core=${coreSig}`);
}
for (const tc of [
  { name: 'u64-max', amount: '18446744073709551615', dest: '0xDEadBEEf00000000000000000000000000001234', currency: 2 },
  { name: 'utf8-dest', amount: '9007199254740993', dest: 'bc1qünïcödé漢字', currency: 1 },
]) {
  // The page's signer derives from_pub from the SEED (the core's rule); give the oracle the same
  // from (via the page's own pubkeyHex, checked below) so both sign identical bytes.
  const from = exports.pubkeyHex(SECRET);
  const pageSig = exports.signWithdrawalHex(SECRET, from, tc.dest, tc.amount, NONCE, 1700000000, tc.currency);
  const coreSig = await wire.signWithdrawalHex(SECRET, from, tc.dest, BigInt(tc.amount), NONCE, 1700000000, tc.currency);
  if (pageSig !== coreSig) bad(`withdraw sig[${tc.name}]: page=${pageSig} core=${coreSig}`);
}

// --- 4b. pubkey-from-seed (restore-compat: same seed ⇒ same account as the app) --------------
{
  const corePub = await wire.signAuthorizationCode(SECRET, TO, 1n, NONCE, 1n, 0, 'A', '', '')
    .then(q => hex(wire.b64urlDecode(q).slice(260, 292))); // wire trailer carries from_pub
  if (exports.pubkeyHex(SECRET) !== corePub) bad(`pubkeyHex: page=${exports.pubkeyHex(SECRET)} core=${corePub}`);
}

// --- 5. receipt verification under the PIN (the R2 trust anchor) -----------------------------
// The page's verifyReceipt must build the frozen 108-byte claim (w_receipt_claim) and check it
// under the PINNED key only (w_verify_receipt_sig). Fixtures: the frozen layout golden below, and
// wire_layout's core-signed receipt golden (RG, bound as the pin via the seam in step 2).
const GOLDEN_CLAIM_HEX = 'cd'.repeat(16) + 'ab'.repeat(32) + 'ef'.repeat(32)
  + 'd204000000000000'   // amount 1234 le
  + '00000000'           // currency 0 le
  + 'e81f000000000000'   // block_index 8168 le
  + 'a6a3806a00000000';  // settle_ts 1786815398 le
// Provenance: dpay-core ReceiptClaim::signing_bytes, pinned by the crate host test
// (crates/dpay-wasm/src/lib.rs) and mirrored in scripts/check-wasm-core.mjs — the SAME frozen
// layout the canister/FakeLedger sign.
{
  eqBytes(exports.buildReceiptClaim('cd'.repeat(16), 'ab'.repeat(32), 'ef'.repeat(32), 1234, 0, 8168, 1786815398),
    Buffer.from(GOLDEN_CLAIM_HEX, 'hex'), 'receipt claim golden (dpay-core signing_bytes)');
  // claim rebuilt from the layout's receipt golden fields == its frozen signing_bytes
  eqBytes(exports.buildReceiptClaim(RG.nonce_hex, RG.from_hex, RG.to_hex, RG.amount, RG.currency, RG.block_index, RG.settle_ts),
    Buffer.from(RG.signing_hex, 'hex'), 'receipt claim rebuild of wire_layout receipt golden');

  // The relay-shaped receipt JSON the page actually verifies on /pay 2xx.
  const receipt = {
    nonce: RG.nonce_hex, from: RG.from_hex, to: RG.to_hex, amount: String(RG.amount),
    currency: RG.currency, block_index: String(RG.block_index), settle_ts: RG.settle_ts,
    pubkey: RG.public_hex, // the pin compare is hex-insensitive — upper-case must pass too
  };
  if (!exports.verifyReceipt(receipt, RG.sig_hex)) bad('verifyReceipt: core-signed golden must verify under the pinned key');
  const flipped = RG.sig_hex.slice(0, 10) + (RG.sig_hex[10] === '0' ? '1' : '0') + RG.sig_hex.slice(11);
  if (exports.verifyReceipt(receipt, flipped)) bad('verifyReceipt: flipped sig byte must NOT verify');
  if (exports.verifyReceipt({ ...receipt, amount: String(RG.amount + 1) }, RG.sig_hex)) bad('verifyReceipt: tampered amount must NOT verify');
  if (exports.verifyReceipt({ ...receipt, pubkey: 'ab'.repeat(32) }, RG.sig_hex)) bad('verifyReceipt: receipt claiming another pubkey must NOT verify');
  // A sig by a NON-pinned key over the same claim: freshly signed with a throwaway seed via the
  // trusted oracle (also proves our golden's determinism — same seed ⇒ same sig as sig_hex).
  const otherSig = hex(await ed.signAsync(Buffer.from(RG.signing_hex, 'hex'), Buffer.from('22'.repeat(32), 'hex')));
  if (exports.verifyReceipt(receipt, otherSig)) bad('verifyReceipt: sig by a non-pinned key must NOT verify');
  const fresh = hex(await ed.signAsync(Buffer.from(RG.signing_hex, 'hex'), Buffer.from(RG.secret_hex, 'hex')));
  if (fresh !== RG.sig_hex) bad('fixture sanity: re-signing the golden claim with its own seed drifted');
  if (exports.verifyReceipt(null, RG.sig_hex) || exports.verifyReceipt(receipt)) bad('verifyReceipt: null receipt / missing sig must NOT verify');
}

// --- 6. bip39 restore-compat (same 24 words ⇒ same 32-byte seed ⇒ same account as the app) --
const VECTORS = [
  ['00'.repeat(32), 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon art'],
  ['7f'.repeat(32), 'legal winner thank year wave sausage worth useful legal winner thank year wave sausage worth useful legal winner thank year wave sausage worth title'],
  ['80'.repeat(32), 'letter advice cage absurd amount doctor acoustic avoid letter advice cage absurd amount doctor acoustic avoid letter advice cage absurd amount doctor acoustic bless'],
  ['ff'.repeat(32), 'zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo vote'],
  ['030a11181f262d343b424950575e656c737a81888f969da4abb2b9c0c7ced5dc', 'adapt explain ecology dinner glare old unfair empty expect road off suggest dash dolphin captain version oval census uncover inform arrest trash first nice'],
];
for (const [entropy, phrase] of VECTORS) {
  const words = phrase.split(' ');
  const got = exports.entropyToMnemonic(Uint8Array.from(Buffer.from(entropy, 'hex')));
  if (got.join(' ') !== phrase) bad(`bip39 encode ${entropy.slice(0, 8)}…: ${got.slice(0, 4).join(' ')}…`);
  const back = hex(exports.mnemonicToEntropy(words));
  if (back !== entropy) bad(`bip39 decode ${entropy.slice(0, 8)}…: ${back}`);
  if (!exports.validateMnemonic(words)) bad(`bip39 validate rejected a canonical vector (${entropy.slice(0, 8)}…)`);
}
// corruption must be caught (restore UI relies on this to refuse a mistyped word)
{
  const w = VECTORS[4][1].split(' '); w[5] = w[5] === 'sausage' ? 'abandon' : 'sausage';
  if (exports.validateMnemonic(w)) bad('bip39: a corrupted mnemonic passed validation');
  if (exports.validateMnemonic(VECTORS[0][1].split(' ').slice(0, 23))) bad('bip39: 23 words passed validation');
}

if (fail) {
  console.error(`\nFAIL: wallet.html wasm-binding/bip39 drifted from dpay-core in ${fail} check(s).`);
  console.error("The web wallet's signatures/refusals, receipt verification, and restore-compat are broken. Fix the guarded block to match e2e/harness/wire.mjs + the staged dpay-core.wasm.");
  process.exit(1);
}
console.log(`wallet-wire parity OK: wasm-backed request/signing/withdraw + pinned receipt verify byte-equal to dpay-core + bip39 canonical vectors across ${cases.length} wire + ${VECTORS.length} bip39 cases (incl. UTF-8, 32-byte truncation, u64 > 2^53)`);
