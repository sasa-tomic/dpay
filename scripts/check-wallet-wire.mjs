#!/usr/bin/env node
// Browser-wallet wire parity assertion (the "/wallet signs like the core" invariant).
//
// The browser wallet page (crates/dpay-relay/assets/wallet.html) carries its OWN copy of the wire
// codec + ed25519 signing + BIP-39 codec in a hand-rolled JS block with NO compile-time link to the
// Rust core. If it drifts (wrong offset, lossy u64, bad NUL-padding, wrong sig input), every
// payment the web wallet signs is refused by the ledger — or worse, a RESTORED wallet derives a
// different key than the Android app and "the same 24 words" open a different account.
//
// This script extracts the guarded block between the `// >>> wallet-wire-v1` / `// <<< wallet-wire-v1`
// fences (stable markers: restyling the page never moves them), runs it in a sandbox against the
// SAME vendored noble bundles the page loads (/ed25519.js, /noble-hashes.js, /wordlist.js), and
// asserts byte-equality with the trusted builders in e2e/harness/wire.mjs (which read
// dfx/wire_layout.json generated by the Rust core itself, and whose signatures are cross-validated
// against ed25519-dalek in e2e test 00):
//   - buildRequestBytes  == core 132-byte request           (incl. UTF-8 names, 32-byte truncation)
//   - signAuthorization  == wire.mjs signAuthorizationCode  (same secretHex → same 292-byte wire QR)
//   - withdraw signing   == core WithdrawAuth golden bytes  + same sig as wire.mjs
//   - bip39 codec        == the canonical BIP-39 256-bit vectors (restore-compat with the app)
// Sub-second, zero deps beyond node itself. Usage: node scripts/check-wallet-wire.mjs (0 = parity).
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as wire from '../e2e/harness/wire.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ASSETS = join(ROOT, 'crates/dpay-relay/assets');
const LAYOUT = JSON.parse(readFileSync(join(ROOT, 'dfx/wire_layout.json'), 'utf8'));

let fail = 0;
const bad = (msg) => { fail++; console.error(`DRIFT: ${msg}`); };

// --- 1. extract the guarded block from wallet.html (fail loud if the fence moved) -----------
const html = (() => {
  try { return readFileSync(join(ASSETS, 'wallet.html'), 'utf8'); }
  catch { console.error('FAIL: crates/dpay-relay/assets/wallet.html not found'); process.exit(1); }
})();
const OPEN = '// >>> wallet-wire-v1', CLOSE = '// <<< wallet-wire-v1';
const o = html.indexOf(OPEN), c = html.indexOf(CLOSE);
if (o < 0 || c < 0 || c < o) {
  console.error(`FAIL: could not locate the ${OPEN} … ${CLOSE} fence in wallet.html`);
  process.exit(1);
}
const fence = html.slice(o + OPEN.length, c);

// --- 2. run the vendored noble bundles + the fence in one sandbox ---------------------------
// The vendored files are IIFEs assigning globalThis.<name>; passing a plain object as the shadowed
// `globalThis` parameter captures their exports without touching the real global.
const sandbox = { crypto: globalThis.crypto };
for (const f of ['noble-hashes.js', 'ed25519.js', 'wordlist.js']) {
  new Function('globalThis', readFileSync(join(ASSETS, f), 'utf8'))(sandbox);
}
if (!sandbox.nobleEd25519 || !sandbox.nobleHashes || !sandbox.DPAY_WORDLIST) {
  console.error('FAIL: vendored noble bundles did not export their globals');
  process.exit(1);
}
const exports = new Function(
  'nobleEd25519', 'nobleHashes', 'DPAY_WORDLIST', 'crypto', 'TextEncoder', 'TextDecoder', 'console',
  fence + '\nwireNobleCrypto();\nreturn { buildRequestBytes, buildRequestQR, decodeRequest, signAuthorization, buildWithdrawSigningBytes, signWithdrawalHex, entropyToMnemonic, mnemonicToEntropy, validateMnemonic, stringToWords };',
)(sandbox.nobleEd25519, sandbox.nobleHashes, sandbox.DPAY_WORDLIST, globalThis.crypto, TextEncoder, TextDecoder, console);

const hex = b => Buffer.from(b).toString('hex');
const eqBytes = (a, b, what) => {
  const ha = hex(a), hb = hex(b);
  if (ha !== hb || a.length !== b.length) { bad(`${what}: page len=${a.length} core len=${b.length}\n  page: ${ha.slice(0, 200)}…\n  core: ${hb.slice(0, 200)}…`); return false; }
  return true;
};

// --- 3. request-encoder parity across the case matrix ---------------------------------------
const TO = 'ab'.repeat(32), NONCE = 'cd'.repeat(16);
const SECRET = LAYOUT.golden.secret_hex; // a fixed key so sigs are comparable case-to-case
const cases = [
  // The layout's two goldens use DIFFERENT memos: request_hex carries (Bob, coffee); wire_hex
  // (sig included) carries (Alice→Bob, dinner). Model them as separate cases, each pinned to its
  // own golden, plus adversarial shapes.
  { name: 'golden-request', to: LAYOUT.golden.to_hex, amount: 2500, nonce: LAYOUT.golden.nonce_hex, expiry: LAYOUT.golden.expiry, currency: 0, from: 'Alice', toName: 'Bob', memo: 'coffee', goldenReq: true },
  { name: 'golden-wire', to: LAYOUT.golden.to_hex, amount: 2500, nonce: LAYOUT.golden.nonce_hex, expiry: LAYOUT.golden.expiry, currency: 0, from: 'Alice', toName: 'Bob', memo: 'dinner', goldenWire: true },
  { name: 'utf8', to: TO, amount: 1, nonce: NONCE, expiry: 1234567890, currency: 1, from: 'ünïcödé nàme 漢字 ok?', toName: 'Café Demo', memo: 'grüß dich ✓' },
  { name: 'u64-2^52-1', to: TO, amount: 4503599627370495, nonce: NONCE, expiry: 1700000000, currency: 2, from: 'A', toName: 'B', memo: '' },
  { name: 'u64-2^63+', to: TO, amount: (2n ** 63n + 123456789n).toString(), nonce: NONCE, expiry: 1700000000, currency: 3, from: 'A', toName: 'B', memo: '' },
  { name: 'u64-max', to: TO, amount: '18446744073709551615', nonce: NONCE, expiry: 1, currency: 0, from: '', toName: '', memo: '' },
  { name: 'trunc-32', to: TO, amount: 500, nonce: NONCE, expiry: 1700000000, currency: 4294967295, from: 'x'.repeat(40), toName: 'y'.repeat(40), memo: 'z'.repeat(40) },
];
for (const tc of cases) {
  const pageReq = exports.buildRequestBytes(tc.to, tc.amount, tc.nonce, tc.expiry, tc.currency, tc.toName, tc.memo);
  const coreReq = wire.buildRequestBytes(tc.to, BigInt(tc.amount), tc.nonce, BigInt(tc.expiry), tc.currency, tc.toName, tc.memo);
  if (pageReq.length !== wire.REQUEST_LEN) bad(`request ${tc.name}: len ${pageReq.length} != ${wire.REQUEST_LEN}`);
  eqBytes(pageReq, coreReq, `request[${tc.name}] bytes`);
  if (tc.goldenReq) eqBytes(pageReq, Buffer.from(LAYOUT.golden.request_hex, 'hex'), 'golden request bytes');
  // decode round-trip (the Pay tab parses merchant QRs with this)
  const dec = exports.decodeRequest(exports.buildRequestQR(tc.to, tc.amount, tc.nonce, tc.expiry, tc.currency, tc.toName, tc.memo));
  const wantAmt = BigInt(tc.amount).toString();
  if (dec.toHex !== tc.to || dec.amount !== wantAmt || dec.nonceHex !== tc.nonce || dec.expiry !== BigInt(tc.expiry).toString()
    || dec.currency !== tc.currency || dec.toName !== tc.toName.slice(0, 32) || dec.memo !== tc.memo.slice(0, 32)) {
    bad(`decode[${tc.name}] round-trip: ${JSON.stringify(dec)}`);
  }
  // signing parity: same secretHex → byte-identical 292-byte wire QR (async core vs sync page)
  const pageQr = exports.signAuthorization(SECRET, tc.to, tc.amount, tc.nonce, tc.expiry, tc.currency, tc.from, tc.toName, tc.memo);
  const coreQr = await wire.signAuthorizationCode(SECRET, tc.to, BigInt(tc.amount), tc.nonce, BigInt(tc.expiry), tc.currency, tc.from, tc.toName, tc.memo);
  if (pageQr !== coreQr) bad(`sign[${tc.name}]: page wire QR != wire.mjs wire QR\n  page: ${pageQr.slice(0, 80)}…\n  core: ${coreQr.slice(0, 80)}…`);
  if (Buffer.from(wire.b64urlDecode(pageQr)).length !== wire.WIRE_LEN) bad(`sign[${tc.name}]: wire len != ${wire.WIRE_LEN}`);
  if (tc.goldenWire) {
    eqBytes(wire.b64urlDecode(pageQr), Buffer.from(LAYOUT.golden.wire_hex, 'hex'), 'golden 292-byte wire (sig included)');
  }
}

// --- 4. withdraw-signing parity --------------------------------------------------------------
const WG = LAYOUT.withdraw.golden;
{
  const pageBuf = exports.buildWithdrawSigningBytes(WG.public_hex, WG.destination, WG.amount, WG.nonce_hex, WG.expiry, WG.currency);
  eqBytes(pageBuf, Buffer.from(WG.signing_hex, 'hex'), 'withdraw golden signing bytes');
  const pageSig = exports.signWithdrawalHex(WG.secret_hex, WG.public_hex, WG.destination, WG.amount, WG.nonce_hex, WG.expiry, WG.currency);
  const coreSig = await wire.signWithdrawalHex(WG.secret_hex, WG.public_hex, WG.destination, WG.amount, WG.nonce_hex, WG.expiry, WG.currency);
  if (pageSig !== coreSig || pageSig !== WG.sig_hex) bad(`withdraw golden sig: page=${pageSig} core=${coreSig}`);
}
for (const tc of [
  { name: 'u64-max', amount: '18446744073709551615', dest: '0xDEadBEEf00000000000000000000000000001234', currency: 2 },
  { name: 'utf8-dest', amount: '9007199254740993', dest: 'bc1qünïcödé漢字', currency: 1 },
]) {
  const pageSig = exports.signWithdrawalHex(SECRET, TO, tc.dest, tc.amount, NONCE, 1700000000, tc.currency);
  const coreSig = await wire.signWithdrawalHex(SECRET, TO, tc.dest, BigInt(tc.amount), NONCE, 1700000000, tc.currency);
  if (pageSig !== coreSig) bad(`withdraw sig[${tc.name}]: page=${pageSig} core=${coreSig}`);
}

// --- 5. bip39 restore-compat (same 24 words ⇒ same 32-byte seed ⇒ same account as the app) --
const VECTORS = [
  ['00'.repeat(32), 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon art'],
  ['7f'.repeat(32), 'legal winner thank year wave sausage worth useful legal winner thank year wave sausage worth useful legal winner thank year wave sausage worth title'],
  ['80'.repeat(32), 'letter advice cage absurd amount doctor acoustic avoid letter advice cage absurd amount doctor acoustic avoid letter advice cage absurd amount doctor acoustic bless'],
  ['ff'.repeat(32), 'zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo vote'],
  ['030a11181f262d343b424950575e656c737a81888f969da4abb2b9c0c7ced5dc', 'adapt explain ecology dinner glare old unfair empty expect road off suggest dash dolphin captain version oval census uncover inform arrest trash first nice'],
];
for (const [entropy, phrase] of VECTORS) {
  const words = phrase.split(' ');
  const got = exports.entropyToMnemonic(Uint8Array.from(Buffer.from(entropy, 'hex')));
  if (got.join(' ') !== phrase) bad(`bip39 encode ${entropy.slice(0, 8)}…: ${got.slice(0, 4).join(' ')}…`);
  const back = hex(exports.mnemonicToEntropy(words));
  if (back !== entropy) bad(`bip39 decode ${entropy.slice(0, 8)}…: ${back}`);
  if (!exports.validateMnemonic(words)) bad(`bip39 validate rejected a canonical vector (${entropy.slice(0, 8)}…)`);
}
// corruption must be caught (restore UI relies on this to refuse a mistyped word)
{
  const w = VECTORS[4][1].split(' '); w[5] = w[5] === 'sausage' ? 'abandon' : 'sausage';
  if (exports.validateMnemonic(w)) bad('bip39: a corrupted mnemonic passed validation');
  if (exports.validateMnemonic(VECTORS[0][1].split(' ').slice(0, 23))) bad('bip39: 23 words passed validation');
}

if (fail) {
  console.error(`\nFAIL: wallet.html wire/bip39 drifted from dpay-core in ${fail} check(s).`);
  console.error('The web wallet\'s signatures/refusals and restore-compat are broken. Fix the guarded block to match e2e/harness/wire.mjs.');
  process.exit(1);
}
console.log(`wallet-wire parity OK: request/signing/withdraw byte-equal to dpay-core + bip39 canonical vectors across ${cases.length} wire + ${VECTORS.length} bip39 cases (incl. UTF-8, 32-byte truncation, u64 > 2^53)`);
