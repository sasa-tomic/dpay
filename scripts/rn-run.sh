#!/usr/bin/env bash
# Build + install + run the dpay React Native app on the connected emulator/device, then prove the
# running app actually invoked the shared Rust core (dpay-core via the UniFFI native module).
#
# It builds a self-contained release APK (JS bundled, debug-signed — no Metro server needed),
# installs and launches it, asserts the on-device self-check marker in logcat, and drives the
# Pay -> Approve flow to screenshot the real offline-signed "Paid" state.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
ROOT="$PWD"

export ANDROID_HOME="${ANDROID_HOME:-/home/sat/Android/Sdk}"
export ANDROID_SDK_ROOT="$ANDROID_HOME"
# Respect a valid JAVA_HOME; otherwise (unset, or an inherited-but-bogus value) ask the JVM itself.
[ -x "${JAVA_HOME:-}/bin/javac" ] || export JAVA_HOME="$(java -XshowSettings:properties -version 2>&1 | sed -n 's/.*java\.home = //p')"
export PATH="$ANDROID_HOME/platform-tools:$PATH"
APP_ID=org.kalaj.dpay
SHOTS="$ROOT/app/shots"; mkdir -p "$SHOTS"

echo "== select target device =="
# adb honours $ANDROID_SERIAL for every command; pick the single device, or require a choice.
if [ -z "${ANDROID_SERIAL:-}" ]; then
  mapfile -t DEVS < <(adb devices | awk 'NR>1 && $2=="device"{print $1}')
  if [ "${#DEVS[@]}" -eq 0 ]; then
    echo "FAIL: no device/emulator connected"; exit 1
  elif [ "${#DEVS[@]}" -eq 1 ]; then
    export ANDROID_SERIAL="${DEVS[0]}"
  else
    echo "Multiple devices: ${DEVS[*]}"
    echo "Pick one, e.g.:  ANDROID_SERIAL=${DEVS[0]} just app"
    exit 1
  fi
fi
export ANDROID_SERIAL
echo "   target: $ANDROID_SERIAL"
adb wait-for-device
[ "$(adb shell getprop sys.boot_completed | tr -d '\r')" = "1" ] || { echo "FAIL: device not booted"; exit 1; }

echo "== resync NDK .so + UniFFI binding into the app (single source of truth) =="
bash scripts/ndk-build-ffi.sh >/tmp/ndk.log 2>&1 || { echo "FAIL ndk"; tail -20 /tmp/ndk.log; exit 1; }
mkdir -p app/android/app/src/main/jniLibs app/android/app/src/main/java/uniffi/dpay_ffi
cp -r android/app/src/main/jniLibs/* app/android/app/src/main/jniLibs/
cp crates/dpay-ffi/bindings/kotlin/uniffi/dpay_ffi/dpay_ffi.kt app/android/app/src/main/java/uniffi/dpay_ffi/dpay_ffi.kt

# Bake the default ledger URL to the laptop's Tailscale IP so a real phone on the tailnet reaches it
# (10.0.2.2 only works from the emulator). Editable in-app. Override with DPAY_RELAY_URL.
LEDGER_URL="${DPAY_RELAY_URL:-}"
[ -z "$LEDGER_URL" ] && TSIP="$(tailscale ip -4 2>/dev/null | head -1)" && [ -n "$TSIP" ] && LEDGER_URL="http://$TSIP:8787"
if [ -n "$LEDGER_URL" ]; then
  printf "// generated by scripts/rn-run.sh\nexport const RELAY_DEFAULT = '%s';\n" "$LEDGER_URL" > app/relayConfig.ts
  echo "   ledger URL baked into app: $LEDGER_URL"
fi

echo "== build release APK (bundles JS) =="
cd app/android
./gradlew --console=plain :app:assembleRelease "$@"
cd "$ROOT"
APK="$(ls -t app/android/app/build/outputs/apk/release/*.apk | head -1)"
echo "   APK: ${APK#$ROOT/}  ($(du -h "$APK" | cut -f1))"

echo "== install + launch =="
adb install -r "$APK" >/dev/null
adb logcat -c || true
# Launch via the fully-qualified component: `<applicationId>/<namespace.MainActivity>`. The namespace
# (where MainActivity is declared, build.gradle `namespace`) is NOT necessarily the applicationId
# (the Play/launcher identity) — here namespace=com.dpay but applicationId=org.kalaj.dpay. The bare
# `.MainActivity` shorthand resolves relative to the applicationId and resolves to a non-existent
# class (Error type 3), so the namespace must be prepended explicitly.
ANDROID_NS="$(sed -n 's/.*namespace *=* *"\(.*\)".*/\1/p' app/android/app/build.gradle | head -1)"
adb shell am start -n "$APP_ID/$ANDROID_NS.MainActivity" >/dev/null

echo "== wait for the on-device self-check marker (proves the app called dpay-core) =="
MARK=""
for _ in $(seq 1 30); do
  MARK="$(adb logcat -d 2>/dev/null | grep -m1 'DPAY_SELFCHECK' || true)"
  [ -n "$MARK" ] && break
  sleep 1
done
echo "   $MARK"
echo "$MARK" | grep -q 'DPAY_SELFCHECK PASS' || { echo "FAIL: self-check did not pass"; adb logcat -d | grep -iE 'dpay|ReactNativeJS|AndroidRuntime' | tail -30; exit 1; }

# Best-effort UI drive for screenshots (non-fatal): tap a node by its visible text via uiautomator.
tap_text() {
  local needle="$1"
  adb shell uiautomator dump /sdcard/ui.xml >/dev/null 2>&1 || return 1
  local bounds
  bounds="$(adb shell cat /sdcard/ui.xml 2>/dev/null | tr '>' '\n' | grep -F "$needle" | grep -oE 'bounds="\[[0-9]+,[0-9]+\]\[[0-9]+,[0-9]+\]"' | head -1)"
  [ -n "$bounds" ] || return 1
  local n; n="$(echo "$bounds" | grep -oE '[0-9]+')"
  local x1 y1 x2 y2; read -r x1 y1 x2 y2 <<<"$(echo "$n" | tr '\n' ' ')"
  adb shell input tap $(((x1 + x2) / 2)) $(((y1 + y2) / 2))
  sleep 1
}

shot() { adb exec-out screencap -p > "$SHOTS/$1"; echo "   shot: app/shots/$1"; }

echo "== screenshots =="
sleep 3; shot 01-pay-scan.png   # the scanner screen (points at the merchant's request QR)

echo
echo "== RN app PASSED: running on-device app signed via dpay-core (self-check green) =="
